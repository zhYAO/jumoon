export function nextId(prefix: 'c' | 'cr' | 'co' | 'pr', listLength: number) {
  const n = listLength + 1000;
  if (prefix === 'c') return `JM-2026-${String(n).padStart(4, '0')}`;
  if (prefix === 'cr') return `CR-${String(n).padStart(7, '0')}`;
  if (prefix === 'co') return `CO-${String(n).padStart(7, '0')}`;
  return `PR-${String(n).padStart(4, '0')}`;
}

export function campaignHasFinance(
  campaignId: string,
  cooperations: PrototypeCooperation[],
  payments: PrototypePayment[],
) {
  return (
    cooperations.some((c) => c.campaignId === campaignId) ||
    payments.some((p) => p.campaignId === campaignId)
  );
}

